#!/usr/bin/env python3
"""Generate books/frozen/operations.ts: the frozen text of every operation in the old book.

Source: Xelmar-tech/infrastructure, branch integration/factory, apps/docs/factory/{operations,areas}.
Usage: python3 -I tools/freeze-operations.py <old repo root> books/frozen/operations.ts

Each acceptance line becomes {claim, was}: the old book's test citation, such as
"(backend save.test.ts)", moves into `was` (policy P1). Everything else is copied as written.
"""
import json, os, re, sys

import yaml

root, out = sys.argv[1], sys.argv[2]
book = os.path.join(root, "apps/docs/factory")
areas = {}
for f in sorted(os.listdir(os.path.join(book, "areas"))):
    a = yaml.safe_load(open(os.path.join(book, "areas", f)))
    for op in a.get("operations") or []:
        areas[op] = a["id"]

CITE = re.compile(r"\s*\(((?:backend|sdk|cli|devnet|contracts|telemetry)[^()]*)\)\s*\.?\s*$")

def claim(line):
    m = CITE.search(line)
    if not m:
        return {"claim": line.strip(), "was": []}
    return {"claim": line[: m.start()].strip().rstrip(".") + ".", "was": [p.strip() for p in m.group(1).split(";")]}

ops = {}
for f in sorted(os.listdir(os.path.join(book, "operations"))):
    r = yaml.safe_load(open(os.path.join(book, "operations", f)))
    oid = r["id"]
    ops[oid] = {
        "id": oid,
        "area": areas.get(oid, "unassigned"),
        "command": r.get("command"),
        "title": r.get("title"),
        "sdk": r.get("sdk"),
        "row": r.get("row"),
        "about": r.get("about"),
        "who": r.get("who"),
        "changes": r.get("changes"),
        "notes": r.get("notes") or [],
        "mistakes": r.get("mistakes") or [],
        "returns": r.get("returns") or [],
        "refusals": r.get("refusals") or [],
        "acceptance": [claim(a) for a in (r.get("acceptance") or [])],
        "events": r.get("events") or [],
        "designed": r.get("designed"),
        "source": f"apps/docs/factory/operations/{f}",
    }

body = json.dumps(ops, indent=2, ensure_ascii=False, sort_keys=False, default=str)
with open(out, "w") as fh:
    fh.write("// GENERATED by tools/freeze-operations.py from the old book. Do not edit: regenerate.\n")
    fh.write("// The old book's text of every operation: the list of capabilities the rebuild keeps, and the\n")
    fh.write("// source of each acceptance claim whose behaviour its evals keep. Its spelling (commands, flags,\n")
    fh.write("// --json shapes, refusal codes, wording) is reference for the target's design, not surface\n")
    fh.write("// (decision system.frozen-behaviour). Acceptance lines are claims with their old test citation in `was` (P1).\n\n")
    fh.write("export const frozen = " + body + " as const;\n\n")
    fh.write("export type FrozenId = keyof typeof frozen;\n")
print(f"{len(ops)} operations, {sum(len(o['acceptance']) for o in ops.values())} acceptance lines, "
      f"{sum(1 for o in ops.values() if o['designed'])} with a designed block, "
      f"{sum(1 for o in ops.values() if o['area']=='unassigned')} without an area")
