// The spike's two commands:
//   generate  writes generated/: the event and snapshot JSON Schemas, each thing's page (states, diagram, who may move
//             it, required sections), the snapshot of example/events.jsonl, and the plan's page rendered from it.
//   prove     replays example/events.jsonl, then shows five broken histories refused, each with its reason.
import * as fs from "node:fs";
import * as path from "node:path";
import * as Schema from "effect/Schema";
import { InvalidHistory } from "./language.ts";
import { Event, Snapshot, THINGS, project } from "./view.ts";

const root = path.join(path.dirname(new URL(import.meta.url).pathname), "..");
const log = fs.readFileSync(path.join(root, "example/events.jsonl"), "utf8").trim().split("\n").map((l) => JSON.parse(l));
const NOW = "2026-11-15T19:05:00Z";

const generate = () => {
  const out = (f: string, s: string) => fs.writeFileSync(path.join(root, "generated", f), `${s.trimEnd()}\n`);
  const note = "Generated by spikes/sitrep/src/main.ts generate. Do not edit.";
  out("events.schema.json", JSON.stringify({ $comment: note, ...Schema.toJsonSchemaDocument(Event) }, null, 1));
  out("snapshot.schema.json", JSON.stringify({ $comment: note, ...Schema.toJsonSchemaDocument(Snapshot) }, null, 1));
  const snap = project(log, NOW);
  out("snapshot.json", JSON.stringify(snap, null, 1));
  const pages = Object.entries(THINGS).map(([name, { machine, allowed }]) => [
    `## ${name}`, "", `States: ${machine.states.join(", ")}. Starts ${machine.start.state}, by \`${machine.start.by}\`.`, "",
    "| Event | Made by | Who may |", "|---|---|---|",
    `| ${machine.start.event} | \`${machine.start.by}\` | ${allowed[machine.start.event]!.join(", ")} |`,
    ...Object.values(machine.moves).map((m) => `| ${m.event} | \`${m.by}\` | ${allowed[m.event]!.join(", ")} |`),
    "", "```mermaid", machine.diagram, "```", "",
  ].join("\n"));
  out("things.md", [`<!-- ${note} -->`, "# The conductor's things", "", ...pages].join("\n"));
  const p = snap.plan.fields as Record<string, string | string[]>;
  out("plan.md", [`<!-- ${note} From the event log, never edited. -->`, `# ${p.title}`, "",
    `*${snap.plan.state}, since ${snap.plan.since}, by ${JSON.stringify(snap.plan.history.at(-1)!.by)}*`, "",
    "## Why", "", p.why, "", "## What", "", p.what, "", "## Where it ends", "", p.endState, "", "## Not in this plan", "", p.outOfScope, "",
    ...snap.milestones.flatMap((m) => {
      const f = m.fields as Record<string, string | string[]>;
      return [`## Milestone ${m.id}: ${f.title} (${m.done} of ${m.of} done, ${m.state})`, "", `**Goal.** ${f.goal}`, "", `**Why now.** ${f.why}`, "", `**Done when.** ${f.doneWhen}`, "",
        ...(f.steps as string[]).map((id) => { const s = snap.steps.find((x) => x.id === id)!; return `- ${id} ${(s.fields as Record<string, string>).title}: ${s.state}`; }), ""];
    })].join("\n"));
  console.log("generated/: events.schema.json, snapshot.schema.json, snapshot.json, things.md, plan.md");
};

const prove = () => {
  const snap = project(log, NOW);
  console.log(`replayed ${log.length} events: plan ${snap.plan.state}; milestone 3 ${snap.milestones[0]!.done} of ${snap.milestones[0]!.of};`,
    `needs you: ${snap.needsYou.asks.length} asks, ${snap.needsYou.threads.length} threads; burn-down ${snap.burn.map((b) => b.left).join(" → ")}`);
  const ask = snap.asks[0]!;
  console.log(`ask ${ask.id} is ${ask.state}; its history:`);
  for (const h of ask.history) console.log(`  ${h.at}  ${h.event.padEnd(13)} by ${h.by.kind === "person" ? h.by.person : h.by.kind === "agent" ? h.by.thread : h.by.run}  → ${h.state}`);
  const broken: Array<[string, Array<unknown>]> = [
    ["an agent agrees the plan", [...log, { ...log.find((e) => e._tag === "plan_written"), _tag: "plan_revised", at: "2026-11-15T19:00:00Z" }, { _tag: "plan_agreed", plan: "rebuild", by: { kind: "agent", thread: "session_01S8RF7Ce7ysZNMXvaxLQkix" }, at: "2026-11-15T19:01:00Z" }]],
    ["an agent marks its own step done", [...log, { _tag: "step_proven", step: "3.6", by: { kind: "agent", thread: "session_01S8RF79VUFRRBGBDTzB485K" }, at: "2026-11-15T19:01:00Z", proof: "https://example.com/x" }]],
    ["an ask answered twice", [...log, { _tag: "ask_answered", ask: "ask-measure-plumbing", by: { kind: "person", person: "aaron" }, at: "2026-11-15T19:01:00Z", answer: { chose: "B" } }]],
    ["a milestone without a goal", log.map((e) => e._tag === "milestone_planned" ? { ...e, goal: "" } : e)],
    ["a lane naming a step nobody planned", log.map((e) => e._tag === "lane_opened" ? { ...e, steps: ["3.6", "3.9"] } : e)],
  ];
  for (const [what, l] of broken) {
    try { project(l, NOW); console.log(`NOT refused: ${what}`); process.exitCode = 1; }
    catch (e) { console.log(`refused, ${what}: ${e instanceof InvalidHistory ? e.message : String(e).split("\n")[0]}`); }
  }
};

if (process.argv[2] === "generate") generate(); else prove();
