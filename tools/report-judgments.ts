// Every decision record in the target book, by concept, plus the ones that name Aaron for review.
// Generated from the records, so it never disagrees with the book.

import { records } from "../books/target/index.ts";

type Decision = {
  _kind: "decision"; id: string; title: string; question: string; chosen: string; why: string; source: string;
  options: { label: string; text: string }[]; affects: { _kind: string; id: string }[];
};
type Concept = { _kind: "concept"; id: string };
type Rec = { _kind: string; id: string; concept?: { id: string } };

const all = records as unknown as Rec[];
const decisions = all.filter((r) => r._kind === "decision") as unknown as Decision[];
const concepts = (all.filter((r) => r._kind === "concept") as unknown as Concept[]).map((c) => c.id);
const count = (kind: string) => all.filter((r) => r._kind === kind).length;

// A decision's concept: its id's first segment when that is a concept, else "shared".
const home = (d: Decision) => {
  const first = d.id.split(".")[0] ?? "";
  return concepts.includes(first) ? first : "shared";
};
// The designers and the assembly flagged these for Aaron in their reports; their text need not name him.
// The report fails if one is not a decision in the book.
const FLAGGED = [
  "payroll.scope", "payments.birth-width", "parties.directory-tenancy", "procedures.accounts-admit",
  "documents.acceptance-rewrites", "agents.org-owned", "board.failed-proposal", "equity.acceptance",
  "contacts.members-write", "notices.claim-escrow", "system.size",
];
/** Decisions that carry out one of Aaron's own; they cite him but need nothing from him. */
const CARRIES_OUT = ["rules.frozen-flags-kept", "rules.frozen-flags-built-ins"];
/** Aaron's own decisions are settled, not for his review. */
const byAaron = (d: Decision) => /^Aaron\b/.test(d.source);
const forAaron = (d: Decision) =>
  !byAaron(d) && !CARRIES_OUT.includes(d.id) && (FLAGGED.includes(d.id) || /\baaron\b/i.test(`${d.title} ${d.question} ${d.why} ${d.chosen}`));
const chosenText = (d: Decision) => d.options.find((o) => o.label === d.chosen)?.text ?? d.chosen;
const one = (s: string) => s.replace(/\s+/g, " ").trim();

const out: string[] = [];
out.push("# Judgments in the target book", "");
out.push("Generated by `tools/report-judgments.ts` from the decision records in `books/target`. Do not edit: regenerate.", "");
out.push(`${decisions.length} decisions. The target book holds ${count("concept")} concepts, ${count("table")} tables, ${count("machine")} state machines, ${count("rpc")} rpcs, ${count("flow")} Core SDK flows, ${count("workflow")} workflows, ${count("procedure")} procedures and ${count("operation")} operations.`, "");

const missing = FLAGGED.filter((id) => !decisions.some((d) => d.id === id));
if (missing.length) throw new Error(`flagged for Aaron but not a decision in the book: ${missing.join(", ")}`);
const review = decisions.filter(forAaron);
const his = decisions.filter(byAaron);
out.push(`## Decided by Aaron (${his.length})`, "");
for (const d of his) out.push(`- **${d.id}**: ${one(d.title)}. ${one(chosenText(d))}`);
out.push("");
out.push(`## For Aaron (${review.length})`, "", "Decisions flagged for Aaron's review, or whose text names a call that is his. Each recorded choice stands, and the build follows it, until he changes it; a change goes into the record first.", "");
for (const d of review) out.push(`- **${d.id}**: ${one(d.title)}. Chosen: ${one(chosenText(d))}`);
out.push("");

const groups = ["shared", ...concepts];
for (const g of groups) {
  const ds = decisions.filter((d) => home(d) === g);
  if (!ds.length) continue;
  out.push(`## ${g} (${ds.length})`, "");
  for (const d of ds) {
    out.push(`### ${d.id}: ${one(d.title)}`, "");
    out.push(`- **Question:** ${one(d.question)}`);
    out.push(`- **Chosen:** ${one(chosenText(d))}`);
    out.push(`- **Why:** ${one(d.why)}`, "");
  }
}
console.log(out.join("\n"));
