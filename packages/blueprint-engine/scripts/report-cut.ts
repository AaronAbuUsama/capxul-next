// node --experimental-strip-types packages/blueprint-engine/scripts/report-cut.ts           → writes docs/cut-archive/INDEX.md from docs/cut-archive/index.json
// node --experimental-strip-types packages/blueprint-engine/scripts/report-cut.ts --check    → exits 1 if INDEX.md is stale or the index is wrong
//
// The cut (shared/cut.ts, cut.principle) moves records out of the built blueprint and deletes none: each one goes to
// docs/cut-archive/ with its text intact. index.json lists every record that left: its id, its verdict (reached,
// dropped or parked for a record; archive or parked for a decision), its reason, what carries it, where it went and where
// it came from. This tool regenerates the readable index from it, and fails if the index is not true:
//
// - a record the index lists still exists in the built blueprint (it was moved, so it must be gone);
// - an archive file the index names is missing, or holds neither the record's id nor its export (`<kind>_<id with . and - as _>`,
//   the blueprint's naming; ids a helper makes, such as `dependencies.of-x`, are not literals);
// - an index line has no reason or no verdict;
// - one record is listed twice.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { records } from "../../../blueprint/index.ts";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const INDEX = join(ROOT, "docs/cut-archive/index.json");
const OUT = join(ROOT, "docs/cut-archive/INDEX.md");
const check = process.argv.includes("--check");

type Entry = {
  key: string; kind: string; id: string; step: string; dest: string; verdict: string; reason: string; carriedBy: string;
  archivedTo: string; from: string; whole: boolean; on: string;
};
const entries: Entry[] = existsSync(INDEX) ? (JSON.parse(readFileSync(INDEX, "utf8")) as Entry[]) : [];
const inBlueprint = new Set((records as unknown as { _kind: string; id: string }[]).map((r) => `${r._kind}:${r.id}`));

const problems: string[] = [];
const seen = new Set<string>();
const archiveText = new Map<string, string>();
const read = (p: string) => archiveText.get(p) ?? (archiveText.set(p, existsSync(join(ROOT, p)) ? readFileSync(join(ROOT, p), "utf8") : "").get(p) as string);
for (const e of entries) {
  if (seen.has(e.key)) problems.push(`${e.key}: listed twice`);
  seen.add(e.key);
  if (inBlueprint.has(e.key)) problems.push(`${e.key}: listed as moved to ${e.archivedTo}, but it is still in the built blueprint`);
  if (!e.verdict || !e.reason) problems.push(`${e.key}: no verdict or no reason`);
  const text = read(e.archivedTo);
  if (!text) problems.push(`${e.key}: the archive file ${e.archivedTo} is missing`);
  else if (!text.includes(`id: ${JSON.stringify(e.id)}`) && !text.includes(`export const ${e.kind}_${e.id.replace(/[.-]/g, "_")} =`))
    problems.push(`${e.key}: the archive file ${e.archivedTo} holds neither id ${JSON.stringify(e.id)} nor export ${e.kind}_${e.id.replace(/[.-]/g, "_")}`);
}

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const short = (s: string, n: number) => (s.length > n ? `${s.slice(0, n - 1).trimEnd()}…` : s);
const out: string[] = [];
out.push("# The cut archive: every record that left the built blueprint", "");
out.push(
  "Generated by `packages/blueprint-engine/scripts/report-cut.ts` from `docs/cut-archive/index.json`. Do not edit: regenerate.",
  "",
  "The rule of the cut is decision `cut.principle`: Core and plugs stay in full; what Frappe owns is reached through the door and its",
  "Capxul-native records leave the built blueprint; nothing is deleted, it is moved with its text intact and a reason. Records that wait on",
  "Aaron or on a call are parked under `docs/cut-archive/parked/`. Moved files keep their imports as they were, so those point at the",
  "folder the file was written in (as `docs/as-is/archive/` does) and are outside every typecheck.",
  "",
);
const by = <T,>(xs: T[], f: (x: T) => string) => xs.reduce<Record<string, T[]>>((a, x) => ((a[f(x)] ??= []).push(x), a), {});
const count = (xs: Entry[], f: (e: Entry) => string) => Object.entries(by(xs, f)).map(([k, v]) => `${v.length} ${k}`).join(", ");
out.push(`${entries.length} records have left the built blueprint: ${count(entries, (e) => e.verdict)}.`, "");
const steps = by(entries, (e) => e.dest);
out.push("| Where | Records | Of which |", "|---|---|---|");
for (const [dest, es] of Object.entries(steps)) out.push(`| \`docs/cut-archive/${dest}/\` | ${es.length} | ${count(es, (e) => e.kind)} |`);
out.push("");
for (const [dest, es] of Object.entries(steps)) {
  out.push(`## ${dest} (${es.length})`, "");
  out.push("| Kind | Id | Verdict | Reason | Carried or replaced by | Archived to |", "|---|---|---|---|---|---|");
  const order = ["operation", "decision", "table", "machine", "event", "rpc", "flow", "workflow", "procedure", "invariant", "contract", "integration", "concept", "journey"];
  const sorted = [...es].sort((a, b) => order.indexOf(a.kind) - order.indexOf(b.kind) || a.id.localeCompare(b.id));
  for (const e of sorted) out.push(`| ${e.kind} | \`${e.id}\` | ${e.verdict} | ${cell(short(e.reason, 150))} | ${cell(short(e.carriedBy || "", 120))} | \`${e.archivedTo.replace("docs/cut-archive/", "")}\` |`);
  out.push("");
}
const text = out.join("\n");

if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== text) problems.push("docs/cut-archive/INDEX.md is stale: run packages/blueprint-engine/scripts/report-cut.ts");
  if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
  console.log(`cut archive: ${entries.length} records indexed, none still in the blueprint, INDEX.md current`);
} else {
  writeFileSync(OUT, text);
  writeFileSync(INDEX, JSON.stringify(entries, null, 1) + "\n");
  if (problems.length) { console.error(problems.join("\n")); process.exit(1); }
  console.log(`docs/cut-archive/INDEX.md: ${entries.length} records; ${Object.keys(steps).length} places; all gone from the blueprint`);
}
