// The unmigrated lists themselves: each names files git tracks, each with a positive count, under its ceiling.
const ROOT = fileURLToPath(new URL("../../../", import.meta.url));
const tracked = new Set(Str.split(execFileSync("git", ["ls-files", "-z"], { cwd: ROOT, encoding: "utf8" }), "\0"));

for (const rule of ["owned-values", "declared-names", "decoded-rows"] as const) {
  test(`${rule}: its unmigrated list names tracked files, each with a positive whole count, within its ceiling`, () => {
    const list: Readonly<Record<string, number>> = unmigrated[rule];
    for (const [path, count] of Rec.toEntries(list)) {
      assert.ok(tracked.has(path), `${path} is not a file git tracks`);
      assert.ok(
        Number.isInteger(count) && count > 0,
        `${path}'s count ${String(count)} is not a positive whole number`,
      );
    }
    const total = Arr.reduce(Rec.values(list), 0, (sum, count) => sum + count);
    assert.ok(
      total <= CEILINGS[rule],
      `${rule}'s list holds ${String(total)}, over its ceiling ${String(CEILINGS[rule])}`,
    );
  });
}

type Declared = {
  readonly emits: ReadonlyArray<{ readonly identifier: string }>;
  readonly outcomes: ReadonlyArray<{ readonly tag: string | null }>;
};

// The names declared-names guards, as the blueprint exports them: every operation, refusal, event, outcome and
// starting world. Loaded by URL so this package's types do not take in the blueprint's.
test("the blueprint's declaredNames holds every operation, refusal, event, outcome and starting world", async () => {
  const door = await import(new URL("../../blueprint/src/door.ts", import.meta.url).href);
  const operations: Readonly<Record<string, Declared>> = door.operations;
  const refusals: Readonly<Record<string, unknown>> = door.Errors.refusals;
  const worlds: Readonly<Record<string, { readonly name: string }>> = door.startingWorlds;
  const expected = new Set([
    ...Rec.keys(operations),
    ...Rec.keys(refusals),
    ...Arr.map(Rec.values(worlds), (world) => world.name),
    ...Arr.flatMap(Rec.values(operations), (operation) => Arr.map(operation.emits, (event) => event.identifier)),
    ...Arr.flatMap(Rec.values(operations), (operation) =>
      Arr.flatMap(operation.outcomes, (outcome) => (outcome.tag === null ? [] : [outcome.tag])),
    ),
  ]);
  const names: unknown = door.declaredNames;
  assert.ok(names instanceof Set, "packages/blueprint/src/door.ts exports no declaredNames set");
  assert.deepEqual(new Set(names), expected);
  for (const name of ["world.create", "WorldExists", "invitation_declined", "fresh", "Collected"])
    assert.ok(names.has(name), `${name} is not among the declared names`);
});
