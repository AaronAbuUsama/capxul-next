/** A message holding every one of `parts`, in any order. */
const saying = (...parts: ReadonlyArray<string>): RegExp => {
  const looks = Arr.map(parts, (part) => `(?=[\\s\\S]*${part})`);
  return new RegExp(`^${Arr.join(looks, "")}`, "i");
};
/** Reported for each finding of a listed file that has more than its `n`. */
const grew = (n: number) => ({ message: saying("unmigrated", `\\b${n}\\b`, "must not grow") });
/** Reported once, on the program, for a listed file that has fewer findings than listed. */
const shrank = (actual: number) => ({ message: saying("lower it", `\\b${actual}\\b`), line: 1 });

