// The text of the docs' generated blocks and of the design notes' list, from their owners' facts. Pure, like
// render.ts: values in, Markdown out.
import * as Arr from "effect/Array";
import * as Rec from "effect/Record";
import * as Str from "effect/String";

/** The width hand-written Markdown here wraps at. */
export const WIDTH = 120;

/** A paragraph wrapped at `WIDTH`, its first line after `first` and the rest after `rest`, breaking only at spaces. */
export const wrap = (text: string, first: string, rest: string): string =>
  Arr.join(
    Arr.reduce(Str.split(text, " "), [] as Array<string>, (lines, word) => {
      const last = lines[lines.length - 1];
      if (last === undefined) return [`${first}${word}`];
      if (last.length + 1 + word.length <= WIDTH) return [...Arr.dropRight(lines, 1), `${last} ${word}`];
      return [...lines, `${rest}${word}`];
    }),
    "\n",
  );

/** The root README's package map: each package, linked, with its reason. */
export const renderPackages = (packages: Readonly<Record<string, string>>): string =>
  Arr.join(
    [
      "| Package | Why it is there |",
      "|---|---|",
      ...Arr.map(Rec.toEntries(packages), ([name, why]) => `| [\`${name}\`](packages/${name}) | ${why} |`),
    ],
    "\n",
  );

/** The gate's table in AGENTS.md: one row per rung. */
export const renderGate = (
  rungs: ReadonlyArray<{ readonly rung: string; readonly command: string; readonly fails: string }>,
): string =>
  Arr.join(
    [
      "| Rung | Command | What fails it |",
      "|---|---|---|",
      ...Arr.map(rungs, ({ rung, command, fails }) => `| ${rung} | ${command} | ${fails} |`),
    ],
    "\n",
  );

/** The list of our lint rules: each by its name, with what it finds. */
export const renderRules = (rules: ReadonlyArray<readonly [string, string]>): string =>
  Arr.join(
    Arr.map(rules, ([name, description]) => wrap(`\`${name}\`: ${description}`, "- ", "  ")),
    "\n",
  );

/** A design note: its file's name in the folder and its text. */
export interface Note {
  readonly name: string;
  readonly text: string;
}

/** A design note's status: the first sentence of its `Status:` paragraph among its first 10 lines, if it has one. */
export const statusOf = (text: string): string | undefined => {
  const lines = Str.split(text, "\n");
  const at = Arr.findFirstIndex(Arr.take(lines, 10), Str.startsWith("Status:"));
  if (at._tag === "None") return undefined;
  const paragraph = Arr.join(
    Arr.takeWhile(Arr.drop(lines, at.value), (line) => Str.trim(line) !== ""),
    " ",
  );
  const said = Str.trim(Str.replaceAll("**", "")(Str.slice("Status:".length)(paragraph)));
  const sentence = /^(.+?[.!?])(\s|$)/.exec(said);
  return sentence === null ? said : (sentence[1] ?? said);
};

const titleOf = (note: Note): string => {
  const title = Arr.findFirst(Str.split(note.text, "\n"), Str.startsWith("# "));
  return title._tag === "Some" ? Str.trim(Str.slice(2)(title.value)) : note.name;
};

/** The design notes' list: one line per note, its title linked, then its status. */
export const renderDesignIndex = (from: string, notes: ReadonlyArray<Note>): string =>
  `<!-- Generated by \`pnpm generate\` from ${from}. Never edit it: change those and run \`pnpm generate\`. -->\n` +
  "# Design notes\n\n" +
  wrap(
    "One note per question, each saying near its top whether it is open, agreed or superseded " +
      "(`packages/lint/src/docs.ts` checks it).",
    "",
    "",
  ) +
  "\n\n" +
  Arr.join(
    Arr.map(notes, (note) => {
      const status = statusOf(note.text);
      return `- [${titleOf(note)}](${note.name}). ${status === undefined ? "No status yet." : `Status: ${status}`}`;
    }),
    "\n",
  ) +
  "\n";
