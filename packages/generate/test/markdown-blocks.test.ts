// Blocks between markers in hand-written Markdown, and the docs' generated text: only the lines between a block's
// markers change, and the committed docs hold what generating again writes.
import { strict as assert } from "node:assert";
import { readdirSync, readFileSync } from "node:fs";
import { test } from "node:test";
import * as Arr from "effect/Array";
import * as Str from "effect/String";
import { renderDesignIndex, renderLadder, renderPackages, renderRules, statusOf, wrap } from "../src/docs-render.ts";
import { markers, renderDocs, replaceBlock } from "../src/markdown-blocks.ts";

const { start, end } = markers("x");

test("a block's lines are replaced, and everything outside its markers is kept", () => {
  const text = `# Title\n\nBefore.\n\n${start}\nold\nlines\n${end}\n\nAfter.\n`;
  assert.deepEqual(replaceBlock(text, "x", "the owner", "new"), {
    _tag: "Replaced",
    text: `# Title\n\nBefore.\n\n${start}\n<!-- Written by \`pnpm generate\` from the owner; never edit it. -->\nnew\n${end}\n\nAfter.\n`,
  });
});

test("replacing a block twice changes nothing more", () => {
  const once = replaceBlock(`${start}\n${end}\n`, "x", "o", "body");
  assert.equal(once._tag, "Replaced");
  if (once._tag === "Replaced") assert.deepEqual(replaceBlock(once.text, "x", "o", "body"), once);
});

test("a block whose markers are missing, repeated or reversed is not placed", () => {
  assert.equal(replaceBlock("no markers", "x", "o", "b")._tag, "Unplaced");
  assert.equal(replaceBlock(`${start}\n${start}\n${end}\n`, "x", "o", "b")._tag, "Unplaced");
  assert.equal(replaceBlock(`${end}\n${start}\n`, "x", "o", "b")._tag, "Unplaced");
});

test("a paragraph wraps at 120 columns, only at spaces", () => {
  const words = Arr.join(
    Arr.makeBy(40, (i) => `word${i}`),
    " ",
  );
  const lines = Str.split(wrap(words, "- ", "  "), "\n");
  assert.ok(Arr.every(lines, (line) => line.length <= 120));
  assert.ok(Str.startsWith("- word0")(lines[0]) && Str.startsWith("  word")(lines[1] ?? ""));
  assert.equal(
    Arr.join(
      Arr.map(lines, (line) => Str.slice(2)(line)),
      " ",
    ),
    words,
  );
});

test("the tables and the list hold each fact given", () => {
  assert.equal(
    renderPackages({ a: "why a" }),
    "| Package | Why it is there |\n|---|---|\n| [`a`](packages/a) | why a |",
  );
  assert.match(
    renderLadder([{ rung: "1. Shape", command: "`pnpm shape`", fails: "x" }]),
    /\n\| 1\. Shape \| `pnpm shape` \| x \|$/,
  );
  assert.equal(renderRules([["capxul/a", "finds a."]]), "- `capxul/a`: finds a.");
});

test("a design note's status is the first sentence of its status paragraph", () => {
  assert.equal(statusOf("# A\n\nStatus: **agreed**, 15 November 2026. More.\n"), "agreed, 15 November 2026.");
  assert.equal(
    statusOf("# A\n\nStatus: open, from the\nexplorer (claude.ai/x). Then.\n"),
    "open, from the explorer (claude.ai/x).",
  );
  assert.equal(statusOf("# A\n\nNo status.\n"), undefined);
  const index = renderDesignIndex("the notes", [
    { name: "a.md", text: "# Note A\n\nStatus: open.\n" },
    { name: "b.md", text: "# Note B\n" },
  ]);
  assert.match(index, /^<!-- Generated by `pnpm generate` from the notes\./);
  assert.match(index, /\n- \[Note A\]\(a\.md\)\. Status: open\.\n- \[Note B\]\(b\.md\)\. No status yet\.\n$/);
});

test("the committed docs hold what generating again writes", () => {
  const root = `${import.meta.dirname}/../../..`;
  const docs = renderDocs({
    read: (path) => readFileSync(`${root}/${path}`, "utf8"),
    list: (folder) => readdirSync(`${root}/${folder}`),
  });
  assert.deepEqual(docs.problems, []);
  for (const [path, text] of docs.written) assert.equal(readFileSync(`${root}/${path}`, "utf8"), text, path);
});
