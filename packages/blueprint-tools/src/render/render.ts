// Renders the blueprint's pages from its declarations, into packages/blueprint/generated/: index.md, with what every
// promise shares, the map of every thing and its verbs, and the starting points; and one page per thing, with its
// lifecycle and each of its verbs' promises, refusals, events and budget, so that a change to one thing renders only
// its own page. Pure: `render.entry.ts` writes the files, and a test compares each with this. It imports the
// blueprint's door by its path (see README.md), so the toolkit's own door (src/index.ts) never exports it.
import {
  allClaims,
  machines,
  operations,
  servedBy,
  startingWorlds,
  type OperationName,
} from "../../../blueprint/src/index.ts";
import * as Arr from "effect/Array";
import { pipe } from "effect/Function";
import * as Option from "effect/Option";
import * as Rec from "effect/Record";
import { refusalsOf, type Operation } from "../language/operation.ts";
import type { Claim, ClaimsOf } from "../language/promise.ts";
import type { Layout, Thing } from "./layout.ts";
import { machinesSection } from "./machines.ts";

const code = (text: string) => `\`${text}\``;
const list = (items: ReadonlyArray<string>) => (items.length === 0 ? "none" : Arr.join(items, ", "));

/** The first line of every page: it is written, never edited. */
const GENERATED =
  "<!-- Generated by `pnpm claims` (packages/blueprint-tools) from packages/blueprint/src. Do not edit. -->";

const header = `${GENERATED}
# The blueprint, thing by thing

Rendered from the declarations by \`pnpm claims\`: this page, and one page per thing beside it with each of its verbs'
promises (today's word in the code: claims). Do not edit them by hand: a test fails when a page and its sources differ.

Each claim is checked black-box by the journeys (\`packages/scenarios\`; docs/roadmap.md, "Scenarios are journeys"):
through the door, reading only what the operations answer and what the world's door shows of its chain. No claim has
a scenario of its own. Its operation's checks run on every call of that operation in every journey, and the journeys'
steps call it as the claim says; \`packages/scenarios/src/coverage.ts\` names, for each claim, the checks and the
steps. "In" names the starting world whose state a claim speaks of: a journey checks it in that state, whether it
starts from that world or starts earlier and brings its world there by its own steps. "Old" names the claim of the old
blueprint (\`docs/thin-line/operations.json\`, its \`evalId\`) it keeps, word for word or rewritten.

## What the runner checks on every call

These hold for every call of every journey, so no claim repeats them:

1. A successful call emits exactly the events its outcome declares, each once, each carrying exactly what the
   declaration computes from the call's payload and answer, and nothing more. A refused call emits none.
2. A refusal is one the operation declares.
3. The call's spans are recorded under the trace id the caller sent, the first named after the operation.
4. The call's time, as the caller saw it and as the server's span measured it, is stored with the run, with the
   time of each step beneath it, next to the operation's budget. A budget is recorded, not enforced: nothing fails
   on speed until a budget is set from measured runs.
`;

const origin = (claim: Claim): ReadonlyArray<string> => {
  if (claim.origin === null) return ["   - Old: none; this claim is new."];
  if (claim.origin.kept === "word for word") return [`   - Old: ${code(claim.origin.id)}, kept word for word.`];
  return [`   - Old: ${code(claim.origin.id)}, rewritten. It said: "${claim.origin.was}" Why: ${claim.origin.why}`];
};

const budget = (operation: Operation) =>
  `${operation.budget.ms.toLocaleString("en-GB")} ms, ${operation.budget.provisional ? "provisional" : "measured"}` +
  (operation.budget.excludes.length > 0 ? `, excluding ${Arr.join(operation.budget.excludes, " and ")}` : "") +
  `. Basis: ${operation.budget.basis}.`;

const emits = (operation: Operation) =>
  pipe(
    operation.outcomes,
    Arr.map(
      (outcome) =>
        `${outcome.tag === null ? "" : `${code(outcome.tag)}: `}${list(Arr.map(outcome.emits, (event) => code(event.identifier)))}`,
    ),
    Arr.join("; "),
  );

const section = (name: OperationName, index: number, of: ClaimsOf): string => {
  const operation: Operation = operations[name];
  const lines = [
    `## ${index + 1}. ${code(name)}`,
    "",
    `- Served by: the ${servedBy(name)} group.`,
    `- Refusals: ${list(Arr.map(refusalsOf(operation), (refusal) => code(refusal.identifier)))}, and ${code("NotSignedIn")} from sign-in.`,
    `- Emits: ${emits(operation)}.`,
    `- Budget: ${budget(operation)}`,
    "",
    ...Arr.flatMap(of.claims, (claim, n) => [
      `${n + 1}. ${claim.says}${claim.thinLine ? " *(thin line)*" : ""}`,
      `   - In: ${code(claim.state.name)}.`,
      `   - Observes: ${claim.observes}`,
      ...(claim.refusals.length > 0
        ? [`   - Refusals: ${list(Arr.map(claim.refusals, (refusal) => code(refusal.identifier)))}.`]
        : []),
      ...origin(claim),
    ]),
  ];
  if (of.dropped.length > 0) {
    lines.push("", "Old claims not kept:", "");
    for (const each of of.dropped) lines.push(`- ${code(each.id)}: "${each.was}" Why: ${each.why}`);
  }
  return Arr.join(lines, "\n");
};

/** Some operations, each with its claims. */
type Claimed = ReadonlyArray<readonly [OperationName, ClaimsOf]>;

const summary = (claimed: Claimed): string => {
  const rows = Arr.map(claimed, ([name, { claims, dropped }]) => {
    const by = (kind: string | null) => Arr.filter(claims, (claim) => (claim.origin?.kept ?? null) === kind).length;
    return `| ${code(name)} | ${claims.length} | ${by("word for word")} | ${by("rewritten")} | ${by(null)} | ${dropped.length} |`;
  });
  return Arr.join(
    [
      "| Operation | Claims | Old, word for word | Old, rewritten | New | Old, not kept |",
      "|---|---|---|---|---|---|",
      ...rows,
    ],
    "\n",
  );
};

/** The names of a facts schema's fields. */
const fieldsOf = (facts: unknown): ReadonlyArray<string> =>
  (typeof facts === "object" || typeof facts === "function") &&
  facts !== null &&
  "fields" in facts &&
  typeof facts.fields === "object" &&
  facts.fields !== null
    ? Rec.keys({ ...facts.fields })
    : [];

const worlds = (): string =>
  pipe(
    Rec.values(startingWorlds),
    Arr.map((world) => {
      const from = world.from === null ? "" : ` Made from ${code(world.from.name)}.`;
      const steps = Arr.map(
        world.steps,
        (step) =>
          `${step.operation === "wait" ? "wait" : code(step.operation)} as ${step.as}: ${step.does}` +
          (step.fact === null ? "" : ` (fact ${code(step.fact)})`),
      );
      const added = Arr.filter(fieldsOf(world.facts), (field) => !fieldsOf(world.from?.facts).includes(field));
      return (
        `- ${code(world.name)}.${from} ${world.holds}${steps.length > 0 ? ` Steps: ${Arr.join(steps, "; ")}.` : ""}` +
        ` A journey from it gets it ${world.made === "from its template" ? "from its template" : "made by its steps"}.` +
        (added.length > 0 ? ` Facts it adds: ${Arr.join(Arr.map(added, code), ", ")}.` : "")
      );
    }),
    Arr.join("\n"),
  );

/** The verbs of `thing`, by their operations' names, in the order of `operations`. */
const namesOf = (thing: Thing): ReadonlyArray<OperationName> =>
  Arr.filter(Rec.keys(operations), (name) => Arr.some(thing.verbs, (verb) => verb.operation === name));

const map = (layout: Layout): string =>
  Arr.join(
    [
      "## The things",
      "",
      "Each thing is a folder, `src/things/<thing>/`, and each of its verbs a file there. An operation keeps its name of",
      "today until the glossary's renames (roadmap item 3.8).",
      "",
      "| Thing | Verb | Operation | Served by |",
      "|---|---|---|---|",
      ...Arr.flatMap(layout.things, (thing) =>
        Arr.flatMap(namesOf(thing), (name) =>
          Arr.map(
            Arr.filter(thing.verbs, (verb) => verb.operation === name),
            (verb) =>
              `| [${thing.name}](${thing.name}.md) | ${verb.verb} | ${code(name)} | the ${servedBy(name)} group |`,
          ),
        ),
      ),
    ],
    "\n",
  );

const index = (layout: Layout): string =>
  Arr.join(
    [
      header,
      map(layout),
      "",
      "## Starting worlds",
      "",
      "Declared in `src/starting-points/points.ts`. Each is made through the door from the one before it, then either saved as a template that a journey starting from it gets (the runner's one world reset in place to it), or made by its steps for each journey. A journey reads the facts of its world, and of every world it is made from, with `given` (decisions.md, 38).",
      "",
      worlds(),
      "",
    ],
    "\n",
  );

const ofThing = (thing: Thing, claimed: Claimed, own: Parameters<typeof machinesSection>[0]): string =>
  Arr.join(
    [
      GENERATED,
      `# The thing ${code(thing.name)}`,
      "",
      `Rendered from \`src/things/${thing.name}/\` by \`pnpm claims\`: each verb's file holds its declaration and its`,
      "promises. Do not edit it by hand: a test fails when this page and its sources differ. What the runner checks on",
      "every call, and the starting worlds a promise is in, are in [index.md](index.md).",
      "",
      "## Count",
      "",
      summary(claimed),
      "",
      ...machinesSection(own),
      ...Arr.map(claimed, ([name, of], n) => `${section(name, n, of)}\n`),
    ],
    "\n",
  );

/** One rendered file: its path from the package's root, and its text. */
export interface Rendered {
  readonly path: string;
  readonly text: string;
}

/** The lifecycle of `thing`, by its machine's name, when it has one. */
const lifecycleOf = (thing: Thing): Parameters<typeof machinesSection>[0] => {
  const every: Parameters<typeof machinesSection>[0] = machines;
  const name = thing.lifecycle?.name;
  return pipe(
    Option.fromNullishOr(name === undefined ? undefined : every[name]),
    Option.match({ onNone: () => ({}), onSome: (machine) => ({ [machine.name]: machine }) }),
  );
};

/** generated/index.md, then each thing's page, in the things' order. Paths are from the blueprint's package root. */
export const renderClaims = (layout: Layout): ReadonlyArray<Rendered> => [
  { path: "generated/index.md", text: index(layout) },
  ...Arr.map(layout.things, (thing) => ({
    path: `generated/${thing.name}.md`,
    text: ofThing(
      thing,
      Arr.map(namesOf(thing), (name) => [name, allClaims[name]] as const),
      lifecycleOf(thing),
    ),
  })),
];
