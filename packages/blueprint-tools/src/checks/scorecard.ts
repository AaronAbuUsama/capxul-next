// The scorecard (roadmap item 3.11; docs/design/blueprint.md, part 14): every thing of the blueprint against every
// format and per-thing ratchet, each cell ✓, ✗, "not yet measured", or "—" where it does not apply; and every
// ratchet's count beneath. Rendered from the thing folders (the layout), the formats and the ratchet lists, so it
// never drifts. Pure: ratchets.entry.ts writes it to packages/blueprint/generated/scorecard.md inside `pnpm generate`.
import * as Arr from "effect/Array";
import * as Rec from "effect/Record";
import * as Str from "effect/String";
import type { Layout, Thing } from "../render/layout.ts";
import type { Format } from "./format.ts";
import { countText, type Tally } from "./ratchets.ts";

const YES = "✓";
const NO = "✗";
const UNMEASURED = "not yet measured";
const NONE = "—";

/** What the scorecard reads beside the layout. */
export interface ScorecardInputs {
  readonly layout: Layout;
  /** Every format of the delta check, by name. */
  readonly formats: { readonly [format: string]: Format };
  /** The files capxul/owned-values still finds raw schemas in (ratchet R1), from the repository's root. */
  readonly rawSchemaFiles: ReadonlyArray<string>;
  /** The operations whose budget is still provisional. */
  readonly provisional: ReadonlyArray<string>;
  readonly tallies: ReadonlyArray<Tally>;
}

/** One column: its heading, what it measures, and a thing's cell. */
interface Column {
  readonly heading: string;
  readonly means: string;
  readonly cell: (thing: Thing) => string;
}

const mark = (ok: boolean): string => (ok ? YES : NO);

const columns = (inputs: ScorecardInputs): ReadonlyArray<Column> => [
  {
    heading: "Lifecycle (R4)",
    means:
      "its lifecycle is declared as a machine, `lifecycle.ts`; — when every verb of it is declared stateless, so it has none",
    cell: (thing) => (thing.lifecycle !== null ? YES : Arr.every(thing.verbs, (verb) => verb.stateless) ? NONE : NO),
  },
  {
    heading: "Full format (R5)",
    means: "every verb of it has every format of the delta check (`src/checks/formats.ts`), none on an unmigrated list",
    cell: (thing) =>
      mark(
        Arr.every(thing.verbs, (verb) =>
          Arr.every(Rec.values(inputs.formats), (format) => format.missing(verb.operation).length === 0),
        ),
      ),
  },
  {
    heading: "Raw schemas (R1)",
    means: "no file of its folder is on capxul/owned-values' unmigrated list",
    cell: (thing) =>
      mark(
        !Arr.some(inputs.rawSchemaFiles, (file) =>
          Str.startsWith(`packages/blueprint/src/things/${thing.name}/`)(file),
        ),
      ),
  },
  {
    heading: "Names as strings (R2)",
    means: "no file outside the blueprint retypes its names; the list is by file, not yet by thing",
    cell: () => UNMEASURED,
  },
  {
    heading: "Rows decoded (R3)",
    means: "Core decodes its stored rows with the blueprint's schemas; the list is by file, not yet by thing",
    cell: () => UNMEASURED,
  },
  {
    heading: "Spans declared (R6)",
    means: "every step of its verbs is a declared span (roadmap item 4.1)",
    cell: () => UNMEASURED,
  },
  {
    heading: "Reached (R9)",
    means: "every move, refusal and outcome it declares is reached by a journey (roadmap item 3.7)",
    cell: () => UNMEASURED,
  },
  {
    heading: "Budgets measured (R13)",
    means: "every verb's budget is set from a measured run, not provisional",
    cell: (thing) => mark(!Arr.some(thing.verbs, (verb) => Arr.contains(inputs.provisional, verb.operation))),
  },
];

const row = (cells: ReadonlyArray<string>): string => `| ${Arr.join(cells, " | ")} |`;

/** The scorecard's text. */
export const renderScorecard = (inputs: ScorecardInputs): string => {
  const all = columns(inputs);
  return Arr.join(
    [
      "<!-- Generated by `pnpm generate` (packages/blueprint-tools, src/checks/scorecard.ts). Do not edit. -->",
      "# The scorecard",
      "",
      "Every thing of the blueprint against every format and per-thing ratchet (roadmap item 3.11). The climb is done",
      "when every cell is ✓ or —. Rendered from the thing folders, the formats and the ratchet lists by `pnpm generate`,",
      "so it never drifts; a test fails while it differs from its sources.",
      "",
      row(["Thing", ...Arr.map(all, (column) => column.heading)]),
      row(Arr.map(["Thing", ...all], () => "---")),
      ...Arr.map(inputs.layout.things, (thing) =>
        row([`[${thing.name}](${thing.name}.md)`, ...Arr.map(all, (column) => column.cell(thing))]),
      ),
      "",
      "## What each column measures",
      "",
      ...Arr.map(all, (column) => `- **${column.heading}**: ${column.means}.`),
      "",
      "## The ratchets",
      "",
      "Declared in `packages/blueprint/src/ratchets.ts`; `pnpm ratchets` fails a pull request whose counted list grew over",
      "its committed count (`ratchets.json`, beside this page). A ratchet gated by a command of its own is reported here",
      "and gated only by that command.",
      "",
      row(["Ratchet", "What its list holds", "Count", "Closes in"]),
      row(["---", "---", "---", "---"]),
      ...Arr.map(inputs.tallies, (tally) =>
        row([`${tally.ratchet.id} ${tally.ratchet.name}`, tally.ratchet.holds, countText(tally), tally.ratchet.closes]),
      ),
      "",
    ],
    "\n",
  );
};
