// The as-is book of the old payments/verifications area: every operation in
// packages/backend/src/payments/verifications/operations/, registered at
// `payments/verifications:<name>` (packages/backend/convex/payments/verifications.ts).
//
// None of them implements a public protocol row: every one is an internal Convex function.
// The verify, settle, sweep-settlements and recover-job actions are scheduled, cron-driven or
// run after another write, so they are workflows; the mutations and the query they run through
// `ctx.runMutation` / `ctx.runQuery` are internal rpcs. A workflow's touches are the union of
// what its rpc steps touch; a step that is itself a workflow (settle under the sweep,
// recover-claims under recover-job) books its own touches.

